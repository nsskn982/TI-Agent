<#
.SYNOPSIS
    Builds the `trading-analyst` Ollama model as a text-only Qwen3.5 variant.
.DESCRIPTION
    Qwen3.5 ships with a vision projector (~650 MB of VRAM) that TI Agent never uses.
    On a 6 GB GPU, weights + 16K KV cache + projector don't fit, and Ollama's
    "retry with projector on CPU" fallback can crash. This script reads the stock
    model definition, keeps only the language-model weights (the largest blob) plus
    the qwen3.5 renderer/parser, which provide tool calling and thinking, and creates
    `trading-analyst` from that.
.EXAMPLE
    .\scripts\create_model.ps1
    .\scripts\create_model.ps1 -BaseModel qwen3.5:9b -NumCtx 32768
#>
[CmdletBinding()]
param(
    [string]$BaseModel = "qwen3.5:4b",
    [string]$Name = "trading-analyst",
    [int]$NumCtx = 16384
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot

# PowerShell 5.1 turns any stderr output from native tools (e.g. Ollama's progress
# spinner) into a terminating error under "Stop". Run them under "Continue" and
# check the exit code instead.
function Invoke-Native {
    param([string]$Exe, [string[]]$Arguments, [string]$What)
    $prev = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try { & $Exe @Arguments 2>&1 | Where-Object { $_ -is [string] } | Out-Host } finally { $ErrorActionPreference = $prev }
    if ($LASTEXITCODE -ne 0) { throw "$What failed (exit code $LASTEXITCODE)." }
}

$ollama = (Get-Command ollama -ErrorAction SilentlyContinue).Source
if (-not $ollama) { $ollama = Join-Path $env:LOCALAPPDATA "Programs\Ollama\ollama.exe" }
if (-not (Test-Path $ollama)) { throw "Ollama not found. Install it from https://ollama.com/download" }

$have = & $ollama list | Select-String -SimpleMatch $BaseModel
if (-not $have) {
    Write-Host "==> Pulling $BaseModel" -ForegroundColor Cyan
    Invoke-Native $ollama @("pull", $BaseModel) "ollama pull"
}

$stock = (& $ollama show $BaseModel --modelfile) -join "`n"
$blobs = [regex]::Matches($stock, "(?m)^FROM\s+(.+)$") | ForEach-Object { $_.Groups[1].Value.Trim() } |
    Where-Object { Test-Path $_ }
if (-not $blobs) { throw "Could not find weight files in 'ollama show $BaseModel --modelfile'." }
# The language model is by far the largest blob; the projector is the smaller one.
$weights = $blobs | Sort-Object { (Get-Item $_).Length } -Descending | Select-Object -First 1
$skipped = @($blobs | Where-Object { $_ -ne $weights })

$keep = [regex]::Matches($stock, "(?m)^(TEMPLATE|RENDERER|PARSER|PARAMETER)\s.+$") |
    ForEach-Object { $_.Value } | Where-Object { $_ -notmatch "^PARAMETER\s+num_ctx" }

$lines = @(
    "# Generated by scripts/create_model.ps1 from $BaseModel (text-only). Do not edit.",
    "FROM $weights"
) + $keep + @("PARAMETER num_ctx $NumCtx")

$out = Join-Path $Root "agent\Modelfile.generated"
Set-Content -Path $out -Value ($lines -join "`n") -Encoding ascii
Write-Host "==> Creating $Name (text-only; skipped $($skipped.Count) projector blob(s), num_ctx $NumCtx)" -ForegroundColor Cyan
Invoke-Native $ollama @("create", $Name, "-f", $out) "ollama create"
& $ollama show $Name | Select-String -Pattern "tools|thinking|vision|context length"
